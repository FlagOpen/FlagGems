@pytest.mark.ccol_indices
def test_accuracy_ccol_indices_mutation_through_view():
    # Real aliasing proof: a write through the returned view must be visible in
    # the sparse tensor's own buffer, and vice versa. A copy (fresh storage)
    # would fail both directions.
    inp = _make_csc((4, 6), 6)
    original = inp.ccol_indices().clone()

    res_out = flag_gems.ccol_indices(inp)
    assert res_out.data_ptr() == inp.ccol_indices().data_ptr()

    res_out[0] = -7
    assert inp.ccol_indices()[0].item() == -7

    # Reverse direction: mutate the tensor's own buffer and observe it through
    # the previously returned view.
    inp.ccol_indices()[1] = -9
    assert res_out[1].item() == -9

    # Restore and confirm the buffers are still identical element-wise.
    res_out.copy_(original)
    assert torch.equal(res_out, inp.ccol_indices())
    utils.gems_assert_equal(res_out, utils.to_reference(inp).ccol_indices())


