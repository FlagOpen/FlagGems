DTYPES = utils.FLOAT_DTYPES + utils.INT_DTYPES + utils.BOOL_TYPES


def _gen_values(nnz, dtype):
    """Values payload for a sparse tensor: any dtype, never checked elementwise."""
    if dtype in utils.FLOAT_DTYPES:
        return torch.randn(nnz, dtype=dtype, device=flag_gems.device)
    if dtype in utils.INT_DTYPES:
        return torch.randint(0, 10, (nnz,), dtype=dtype, device=flag_gems.device)
    return torch.randint(0, 2, (nnz,), dtype=torch.bool, device=flag_gems.device)


def _col_counts(nrows, ncols, nnz):
    """Deterministic column occupancy summing exactly to ``nnz``."""
    counts = [0] * ncols
    for i in range(nnz):
        counts[i % ncols] += 1
    return counts


def _make_csc(shape, nnz, dtype=torch.float32, idx_dtype=torch.int64, device=None):
    """Build a valid CSC tensor (ccol length ncols + 1, col/values length nnz).

    Supports an optional batch prefix: ``shape = batch_dims + (nrows, ncols)``.
    """
    device = flag_gems.device if device is None else device
    nrows, ncols = shape[-2], shape[-1]
    batch = tuple(shape[:-2])
    counts = _col_counts(nrows, ncols, nnz)
    ccol = [0]
    for c in counts:
        ccol.append(ccol[-1] + c)
    # Row indices within each column: distinct rows where possible.
    row = []
    for c, cnt in enumerate(counts):
        row.extend(list(range(cnt)))
    ccol_t = torch.tensor(ccol, dtype=idx_dtype, device=device)
    row_t = torch.tensor(row, dtype=idx_dtype, device=device)
    vals = _gen_values(nnz, dtype)
    if batch:
        ccol_t = ccol_t.unsqueeze(0).repeat(batch + (1,)).contiguous()
        row_t = row_t.unsqueeze(0).repeat(batch + (1,)).contiguous()
        vals = vals.repeat(batch + (1,))
    return torch.sparse_csc_tensor(ccol_t, row_t, vals, size=shape, device=device)


def _make_bsc(shape, block, nnz_blocks, dtype=torch.float32, device=None):
    """Build a valid BSC tensor: block shape ``block``, ccol length n_col_blocks+1."""
    device = flag_gems.device if device is None else device
    nrows, ncols = shape[-2], shape[-1]
    br, bc = block
    r_blks = (nrows + br - 1) // br
    c_blks = (ncols + bc - 1) // bc
    batch = tuple(shape[:-2])
    counts = _col_counts(r_blks, c_blks, nnz_blocks)
    ccol = [0]
    for c in counts:
        ccol.append(ccol[-1] + c)
    row = []
    for c, cnt in enumerate(counts):
        row.extend(list(range(cnt)))
    ccol_t = torch.tensor(ccol, dtype=torch.int64, device=device)
    row_t = torch.tensor(row, dtype=torch.int64, device=device)
    vals = _gen_values(nnz_blocks * br * bc, dtype).reshape((nnz_blocks,) + block)
    if batch:
        ccol_t = ccol_t.unsqueeze(0).repeat(batch + (1,)).contiguous()
        row_t = row_t.unsqueeze(0).repeat(batch + (1,)).contiguous()
        vals = vals.repeat(batch + (1, 1, 1))
    return torch.sparse_bsc_tensor(ccol_t, row_t, vals, size=shape, device=device)


def _make_strided_ccol_csc(shape=(4, 6), nnz=6):
    """CSC whose internal ccol storage is a non-contiguous (interleaved) view.

    Only the constructor's compressed-index argument is interleaved, so
    ``ccol_indices()`` is a strided view -- the branch that proves the metadata
    is handed back verbatim rather than materialised into a contiguous copy.
    Every tensor built through the plain constructor has a contiguous ccol
    array, so this is the only way to reach the strided-metadata case.
    """
    device = flag_gems.device
    nrows, ncols = shape[-2], shape[-1]
    batch = tuple(shape[:-2])
    counts = _col_counts(nrows, ncols, nnz)
    ccol = [0]
    for c in counts:
        ccol.append(ccol[-1] + c)
    row = []
    for c, cnt in enumerate(counts):
        row.extend(list(range(cnt)))
    ccol_t = torch.tensor(ccol, dtype=torch.int64, device=device)
    if batch:
        ccol_t = ccol_t.unsqueeze(0).repeat(batch + (1,))
        store = torch.zeros(
            batch + (ccol_t.shape[-1] * 2,), dtype=torch.int64, device=device
        )
        store[..., ::2] = ccol_t
        ccol_view = store[..., ::2]
    else:
        store = torch.zeros(ccol_t.numel() * 2, dtype=torch.int64, device=device)
        store[::2] = ccol_t
        ccol_view = store[::2]
    assert not ccol_view.is_contiguous()
    row_t = torch.tensor(row, dtype=torch.int64, device=device)
    vals = _gen_values(nnz, torch.float32)
    if batch:
        row_t = row_t.unsqueeze(0).repeat(batch + (1,)).contiguous()
        vals = vals.repeat(batch + (1,))
    return torch.sparse_csc_tensor(ccol_view, row_t, vals, size=shape, device=device)


