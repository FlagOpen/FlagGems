def test_accuracy_ccol_indices_rejects_non_column_compressed(layout, layout_name):
    # Only column-compressed layouts carry a compressed-column buffer. The
    # implementation rejects the remaining standard layouts itself, because the
    # plain device-key registration (added by the general registrar) would make
    # a re-dispatch of a strided input re-enter the implementation instead of
    # reaching the native check.
    #
    # The asserted fragment is taken from this implementation's own documented
    # message (not from the reference's wording); the reference side asserts
    # only that it rejects, since CI's torch build may raise a different
    # subclass from a different code path.
    csc = _make_csc((4, 6), 6)
    if layout == "csr":
        inp = csc.to_sparse_csr()
    elif layout == "bsr":
        inp = _make_bsc((4, 4), (2, 2), 2).to_sparse_bsr((2, 2))
    elif layout == "coo":
        inp = torch.sparse_coo_tensor(
            torch.tensor([[0, 1], [1, 2]], device=flag_gems.device),
            torch.randn(2, device=flag_gems.device),
            (3, 3),
        )
    elif layout == "strided":
        inp = torch.randn(3, 4, device=flag_gems.device)
    elif layout == "strided_noncontig":
        inp = torch.randn(4, 3, device=flag_gems.device).t()
    elif layout == "strided_1d":
        inp = torch.randn(5, device=flag_gems.device)
    elif layout == "strided_0dim":
        inp = torch.tensor(1.0, device=flag_gems.device)
    else:
        inp = torch.empty(0, device=flag_gems.device)

    with pytest.raises(RuntimeError) as res_exc:
        flag_gems.ccol_indices(inp)
    assert "expected sparse column compressed tensor layout" in str(res_exc.value)
    assert f"but got {layout_name}" in str(res_exc.value)

    # Reference side: measured on this build it raises RuntimeError with the
    # same wording, but only "rejects" is asserted here.
    with pytest.raises(Exception):
        torch.ops.aten.ccol_indices(utils.to_reference(inp))


