"""Accuracy tests for ``aten::linalg_inv``.

Inputs are well-conditioned square matrices with batch, scalar and double-precision coverage.
"""

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

DEVICE = flag_gems.device

CASES = [
    ((), 2, torch.float32),
    ((1,), 3, torch.float32),
    ((2,), 4, torch.float64),
    ((2, 3), 5, torch.float32),
    ((1,), 7, torch.float64),
    ((3,), 3, torch.float32),
    ((2, 2), 4, torch.float32),
    ((4,), 6, torch.float64),
    ((1, 2, 1), 3, torch.float32),
    ((2,), 8, torch.float64),
]


def _inputs(case):
    batch_shape, n, dtype = case
    torch.manual_seed(0)
    raw = torch.randn(*batch_shape, n, n, dtype=dtype, device=DEVICE)
    eye = torch.eye(n, dtype=dtype, device=DEVICE).expand(*batch_shape, n, n)
    return raw @ raw.transpose(-1, -2) + 3.0 * eye


@pytest.mark.linalg_inv
@pytest.mark.parametrize("case", CASES)
def test_linalg_inv(case):
    dtype = case[-1]
    if dtype == torch.float64 and not utils.fp64_is_supported:
        pytest.skip("float64 is not supported by this device")
    inputs = _inputs(case)
    ref = torch.ops.aten.linalg_inv.default(utils.to_reference(inputs, True))
    res = flag_gems.linalg_inv(inputs)
    utils.gems_assert_close(res, ref.to(dtype), dtype, reduce_dim=case[1] * case[1])
