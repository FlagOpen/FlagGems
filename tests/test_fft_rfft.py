"""Accuracy tests for ``aten::fft_rfft``."""

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

DEVICE = flag_gems.device

# Float16 cases use power-of-two transform lengths accepted by CUDA FFT.  The
# float64 cases exercise complex128 output with an explicit comparator because
# FlagGems' generic resolution table intentionally only lists complex64.
CASES = [
    ((2, 16), None, -1, None, torch.float16),
    ((1, 32), 32, -1, "ortho", torch.float16),
    ((2, 4, 8), 8, -1, "forward", torch.float16),
    ((3, 31), 48, -1, None, torch.float32),
    ((2, 8, 9), 5, 1, "forward", torch.float32),
    ((3, 4, 5), 7, 0, "ortho", torch.float32),
    ((1, 2, 3, 16), 32, -1, None, torch.float32),
    ((2, 4, 17), 12, -1, "forward", torch.float64),
    ((1, 16), None, -1, "ortho", torch.float64),
    ((2, 8, 8), 8, 1, None, torch.float64),
]


@pytest.mark.fft_rfft
@pytest.mark.parametrize("case", CASES)
def test_fft_rfft(case):
    shape, n, dim, norm, dtype = case
    if dtype == torch.float64 and not utils.fp64_is_supported:
        pytest.skip("float64 is not supported by this device")
    torch.manual_seed(0)
    inp = torch.randn(shape, dtype=dtype, device=DEVICE)
    ref_inp = utils.to_reference(inp)
    if utils.TO_CPU and dtype == torch.float16:
        ref_inp = ref_inp.float()
    ref = torch.ops.aten.fft_rfft.default(ref_inp, n=n, dim=dim, norm=norm)
    res = flag_gems.fft_rfft(inp, n=n, dim=dim, norm=norm)
    if ref.dtype == torch.complex128:
        res = utils.to_cpu(res, ref)
        torch.testing.assert_close(res, ref, rtol=1e-6, atol=1e-4)
    else:
        # The Triton implementation accumulates half input in fp32 and
        # returns complex64; CUDA ATen may expose complex32 for half input.
        if ref.dtype == torch.complex32:
            torch.testing.assert_close(
                res,
                ref.to(torch.complex64),
                rtol=3e-3,
                atol=5e-3,
            )
        else:
            utils.gems_assert_close(res, ref, ref.dtype)
