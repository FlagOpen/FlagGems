"""Correctness tests for the sparse ``values`` and ``_values`` accessors.

Both ``aten::values`` and ``aten::_values`` return a *view aliasing* the stored
values buffer of a sparse tensor, so element-wise equality alone is not enough:
every aliasing case here also checks
``res.data_ptr() == inp._values().data_ptr()``, exactly as native ATen does
(``get_sparse_impl(self)->values().alias()``).

The two operators differ in scope: ``values`` is the public accessor and also
supports the compressed layouts (CSR/CSC/BSR/BSC), while ``_values`` is the
internal accessor implemented only for COO. The registry ids are ``values`` and
``underscore_values`` respectively (the leading underscore of the aten name
cannot be used as a pytest marker).
"""

