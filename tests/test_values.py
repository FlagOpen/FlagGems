def _coalesced_coo(size, nnz, dtype, dense_shape=(), seed=0):
    """Build a coalesced sparse COO tensor with unique, sorted indices."""
    gen = torch.Generator().manual_seed(seed)
    sparse_dim = len(size)
    numel = 1
    for s in size:
        numel *= s
    flat = torch.randperm(numel, generator=gen)[:nnz].sort().values
    indices = torch.empty((sparse_dim, nnz), dtype=torch.int64)
    for d in reversed(range(sparse_dim)):
        indices[d] = flat % size[d]
        flat = flat // size[d]
    values = torch.randn((nnz,) + tuple(dense_shape), dtype=dtype, generator=gen)
    full_size = tuple(size) + tuple(dense_shape)
    return torch.sparse_coo_tensor(indices, values, full_size).coalesce()


def _make_coo(size, nnz, dtype, dense_shape=(), seed=0):
    return _coalesced_coo(size, nnz, dtype, dense_shape, seed).to(flag_gems.device)


