@pytest.mark.values
def test_values_autograd():
    # Native ``values()`` on a requires-grad sparse tensor returns an aliasing
    # tensor carrying ``ValuesBackward0``. This operator replaces the Sparse
    # kernel below the autograd key, so the same wrapping must still happen
    # when the call goes through the dispatcher.
    gen = torch.Generator(device=flag_gems.device).manual_seed(11)
    values = torch.randn(4, generator=gen, device=flag_gems.device).requires_grad_()
    ref_values = values.detach().clone().requires_grad_()
    indices = torch.tensor([[0, 1, 2, 3]], device=flag_gems.device)
    inp = torch.sparse_coo_tensor(indices, values, (6,)).coalesce()
    ref_inp = torch.sparse_coo_tensor(indices, ref_values, (6,)).coalesce()

    ref_out = ref_inp.values()
    with flag_gems.use_gems(include=["values"]):
        res_out = inp.values()

    assert res_out.requires_grad == ref_out.requires_grad
    assert type(res_out.grad_fn) is type(ref_out.grad_fn)
    assert res_out.data_ptr() == inp._values().data_ptr()
    utils.gems_assert_equal(res_out, ref_out)

    (grad,) = torch.autograd.grad(res_out.sum(), values, retain_graph=True)
    (ref_grad,) = torch.autograd.grad(ref_out.sum(), ref_values, retain_graph=True)
    utils.gems_assert_equal(grad, ref_grad)


@pytest.mark.values
def test_values_compressed_layouts_native():
    # Compressed layouts (CSR/CSC/BSR/BSC) keep the untouched native kernel:
    # FlagGems registers ``values`` only for the COO Sparse backends because the
    # values member of a compressed tensor is reachable in Python only through
    # this operator itself (re-entering the dispatcher would recurse). Assert
    # the alias contract still holds through this package.
    dense = torch.zeros((4, 6), device=flag_gems.device)
    dense[0, :2] = 1.0
    dense[1, 2:4] = 2.0
    dense[3, 5] = 3.0

    for layout in ("csr", "csc"):
        inp = getattr(dense, f"to_sparse_{layout}")()
        res = flag_gems.values(inp)
        first = inp.values()
        assert res.data_ptr() == first.data_ptr()
        utils.gems_assert_equal(res, first)

    bsr = dense.to_sparse_bsr((1, 2))
    res = flag_gems.values(bsr)
    assert res.data_ptr() == bsr.values().data_ptr()
    utils.gems_assert_equal(res, bsr.values())
