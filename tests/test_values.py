@pytest.mark.values
def test_values_non_contiguous_values():
    # Native returns the stored values view untouched, strides included, even
    # when that view is non-contiguous; the values are never gathered.
    gen = torch.Generator(device=flag_gems.device).manual_seed(7)
    base = torch.randn((6, 5), generator=gen, device=flag_gems.device)
    # Slice on-device: a host-to-device copy would silently re-contiguous it.
    strided = base[::2]
    assert not strided.is_contiguous()
    inp = torch.sparse_coo_tensor(
        torch.tensor([[0, 1, 2]], device=flag_gems.device), strided, (10, 5)
    )
    # Force the coalesced flag: the indices are already unique and sorted, and
    # ``coalesce()`` would otherwise re-materialize a contiguous buffer.
    inp._coalesced_(True)

    ref_out = utils.to_reference(inp).values()
    res_out = flag_gems.values(inp)

    assert not res_out.is_contiguous()
    assert res_out.stride() == strided.stride()
    _assert_alias(res_out, inp)
    utils.gems_assert_equal(res_out, ref_out)


