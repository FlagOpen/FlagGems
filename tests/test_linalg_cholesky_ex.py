"""Accuracy tests for ``aten::linalg_cholesky_ex``.

Inputs are symmetric positive-definite matrices; `upper` covers both triangular output conventions.
"""

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

DEVICE = flag_gems.device

CASES = [
    ((), 2, False, torch.float32),
    ((1,), 3, True, torch.float32),
    ((2,), 4, False, torch.float64),
    ((2, 3), 5, True, torch.float32),
    ((1,), 7, False, torch.float64),
    ((3,), 3, True, torch.float32),
    ((2, 2), 4, False, torch.float32),
    ((4,), 6, True, torch.float64),
    ((1, 2, 1), 3, False, torch.float32),
    ((2,), 8, True, torch.float64),
]


def _inputs(case):
    batch_shape, n, flag, dtype = case
    torch.manual_seed(0)
    raw = torch.randn(*batch_shape, n, n, dtype=dtype, device=DEVICE)
    eye = torch.eye(n, dtype=dtype, device=DEVICE).expand(*batch_shape, n, n)
    matrix = raw @ raw.transpose(-1, -2) + 2.0 * eye
    return matrix, flag


@pytest.mark.linalg_cholesky_ex
@pytest.mark.parametrize("case", CASES)
def test_linalg_cholesky_ex(case):
    dtype = case[-1]
    if dtype == torch.float64 and not utils.fp64_is_supported:
        pytest.skip("float64 is not supported by this device")
    inputs = _inputs(case)
    ref = torch.ops.aten.linalg_cholesky_ex.default(
        utils.to_reference(inputs[0], True), upper=inputs[1], check_errors=False
    )
    res = flag_gems.linalg_cholesky_ex(inputs[0], upper=inputs[1], check_errors=False)
    ref_L, ref_info = ref
    res_L = res.L if hasattr(res, "L") else res[0]
    res_info = res.info if hasattr(res, "info") else res[1]
    utils.gems_assert_close(res_L, ref_L.to(dtype), dtype, reduce_dim=case[1] * case[1])
    assert torch.equal(res_info.cpu(), ref_info.cpu())
