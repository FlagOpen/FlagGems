@pytest.mark.is_leaf
@pytest.mark.parametrize("dtype", utils.FLOAT_DTYPES + utils.COMPLEX_DTYPES)
@pytest.mark.parametrize(
    "kind",
    [
        "plain",
        "conj",
        "neg",
        "both",
        "transpose",
        "slice",
        "expand",
        "empty",
        "scalar",
        "leaf",
        "computed",
        "detached",
    ],
)
def test_is_leaf(dtype, kind):
    base = torch.zeros((3, 4), dtype=dtype, device=flag_gems.device)
    if kind == "conj":
        inp = base.conj()
    elif kind == "neg":
        inp = torch.ops.aten._neg_view.default(base)
    elif kind == "both":
        inp = torch.ops.aten._neg_view.default(base.conj())
    elif kind == "transpose":
        inp = base.t()
    elif kind == "slice":
        inp = base[:, 1::2]
    elif kind == "expand":
        inp = base[:1].expand(7, 4)
    elif kind == "empty":
        inp = base[:0]
    elif kind == "scalar":
        inp = base[0, 0]
    elif kind in ("leaf", "computed", "detached"):
        base.requires_grad_()
        inp = base if kind == "leaf" else base * 2
        if kind == "detached":
            inp = inp.detach()
    else:
        inp = base
    metadata = (
        inp.shape,
        inp.stride(),
        inp.storage_offset(),
        inp.data_ptr(),
        inp.is_conj(),
        inp.is_neg(),
        inp.is_leaf,
    )
    # Clear lazy flags on an alias before copying the payload: native CUDA
    # cannot materialize a combined conj+neg ComplexHalf view.
    payload = inp.detach()
    if payload.is_conj():
        payload = payload.conj()
    if payload.is_neg():
        payload = torch.ops.aten._neg_view.default(payload)
    snapshot = payload.clone()
    reference = torch.ops.aten.is_leaf.default(inp)
    with _RejectSameOperator():
        result = flag_gems.is_leaf(inp)
    _assert_bool(result, reference)
    assert metadata == (
        inp.shape,
        inp.stride(),
        inp.storage_offset(),
        inp.data_ptr(),
        inp.is_conj(),
        inp.is_neg(),
        inp.is_leaf,
    )
    utils.gems_assert_equal(payload, utils.to_reference(snapshot))


