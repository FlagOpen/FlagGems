"""Accuracy tests for ``aten::linalg_tensorsolve``.

Each case is a square tensorized linear system with a deterministic solution.
"""

import pytest
import torch

import flag_gems

from . import accuracy_utils as utils

DEVICE = flag_gems.device

CASES = [
    ((2, 3, 2, 3), (2, 3), None, torch.float32),
    ((3, 3, 3, 3), (3, 3), None, torch.float64),
    ((2, 2, 2, 2), (2, 2), None, torch.float32),
    ((1, 1), (1,), None, torch.float32),
    ((4, 4), (4,), None, torch.float64),
    ((2, 4, 2, 4), (2, 4), None, torch.float32),
    ((1, 3, 1, 3), (1, 3), None, torch.float64),
    ((3, 2, 3, 2), (3, 2), None, torch.float32),
    ((2, 5, 2, 5), (2, 5), None, torch.float32),
    ((2, 2, 2, 2, 2, 2), (2, 2, 2), None, torch.float64),
]


def _inputs(case):
    lhs_shape, rhs_shape, dims, dtype = case
    torch.manual_seed(0)
    solution_shape = lhs_shape[: -len(rhs_shape)]
    p = 1
    for size in solution_shape:
        p *= size
    raw = torch.randn(p, p, dtype=dtype, device=DEVICE)
    matrix = raw @ raw.T + 2.0 * torch.eye(p, dtype=dtype, device=DEVICE)
    system = matrix.reshape(*lhs_shape)
    solution = torch.randn(*solution_shape, dtype=dtype, device=DEVICE)
    rhs = (matrix @ solution.reshape(-1)).reshape(*rhs_shape)
    return system, rhs, dims


@pytest.mark.linalg_tensorsolve
@pytest.mark.parametrize("case", CASES)
def test_linalg_tensorsolve(case):
    dtype = case[-1]
    if dtype == torch.float64 and not utils.fp64_is_supported:
        pytest.skip("float64 is not supported by this device")
    inputs = _inputs(case)
    ref = torch.ops.aten.linalg_tensorsolve.default(
        utils.to_reference(inputs[0], True),
        utils.to_reference(inputs[1], True),
        dims=inputs[2],
    )
    res = flag_gems.linalg_tensorsolve(inputs[0], inputs[1], dims=inputs[2])
    utils.gems_assert_close(
        res, ref.to(dtype), dtype, reduce_dim=case[0][-1] if case[0] else 1
    )
