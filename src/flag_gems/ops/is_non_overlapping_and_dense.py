import logging

import torch

logger = logging.getLogger(__name__)


def is_non_overlapping_and_dense(self):
    """Check whether strided logical elements cover one dense storage span."""
    logger.debug("GEMS IS_NON_OVERLAPPING_AND_DENSE")
    if self is None:
        return True
    if not isinstance(self, torch.Tensor):
        raise TypeError("is_non_overlapping_and_dense: self must be a Tensor")
    if self.layout != torch.strided or self.is_nested:
        return False
    # TensorBase reads this cached flag without ATen dispatch. Contiguous,
    # empty and singleton descriptors are already known to be dense.
    if self.is_contiguous():
        return True
    # Unit dimensions do not constrain a layout. In increasing stride order,
    # every remaining dimension must extend exactly the previously dense span.
    dims = sorted(
        (stride, size) for size, stride in zip(self.shape, self.stride()) if size > 1
    )
    expected = 1
    for stride, size in dims:
        if stride != expected:
            return False
        expected *= size
    return True
