def _lengths_to_tensor(lengths, device, name):
    """Move per-batch lengths to ``device`` as a 1D int64 tensor.

    Python sequences go through a pinned staging buffer so the host-to-device
    copy is a single asynchronous transfer instead of a pageable one.
    """
    if torch.is_tensor(lengths):
        if not _is_integral_dtype(lengths.dtype):
            raise RuntimeError(f"{name} must be integral")
        out = lengths.to(device=device, dtype=torch.long)
    else:
        staged = torch.tensor(list(lengths), dtype=torch.long, pin_memory=True)
        out = staged.to(device=device, non_blocking=True)
    return out.reshape(1) if out.ndim == 0 else out.reshape(-1).contiguous()


