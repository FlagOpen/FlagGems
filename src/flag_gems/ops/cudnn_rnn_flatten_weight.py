# cudnnRNNMode_t: RNN_RELU=0, RNN_TANH=1, LSTM=2, GRU=3
# The number of "gates" decides how many rows each linear layer matrix has.
_NUM_GATES = {
    0: 1,  # RNN_RELU
    1: 1,  # RNN_TANH
    2: 4,  # LSTM
    3: 3,  # GRU
}

# Weights can be of any dtype; the copy is done bitwise by viewing the buffers
# through an integer type of the same width so the kernel does not need one
# specialization per dtype.
_ELEM_TO_TL_DTYPE = {
    1: tl.int8,
    2: tl.int16,
    4: tl.int32,
    8: tl.int64,
}

# Elements copied per program. Each program copies one contiguous run of a
# single weight tensor, so loads/stores stay vectorized.
BLOCK_SIZE = 2048

# The copy plan only depends on the address/layout of the weight list, which is
# stable across repeated calls on the same RNN module. Caching the uploaded
# descriptor by content keeps the steady-state path free of any host->device
# traffic while staying exact: a cache hit means the bytes on the device are
# already identical to the ones that would be uploaded.
_DESC_CACHE_SIZE = 8

# functools.lru_cache cannot be used here because the rows list contains plain
# ints (hashable) but the cached value is a device tensor that must be kept
# alive; a plain dict with a bounded size does the same job.
_DESC_CACHE = {}


def _descriptor_for(rows, device):
    """Return a device int64 ``[n, 3]`` copy of ``rows``, reusing cached ones."""
    key = tuple(rows)
    desc = _DESC_CACHE.get(key)
    if desc is None:
        if len(_DESC_CACHE) >= _DESC_CACHE_SIZE:
            _DESC_CACHE.clear()
        desc = torch.tensor(rows, dtype=torch.int64, device=device).reshape(-1, 3)
        _DESC_CACHE[key] = desc
    return desc


@triton.jit
def _flatten_weight_kernel(
    seg_ptr,
    out_ptr,
    ELEM_DTYPE: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Copy one tile of one weight tensor into the flat weight buffer.

    ``seg_ptr`` points at a ``[num_segs, 3]`` int64 descriptor holding, for
    every copied run, its source data address, its destination offset inside
    the flat buffer and its length in elements. A source address of ``-1``
    marks a run that must stay zero (cuDNN always reserves room for biases).
    """
    seg = tl.program_id(0)
    tile = tl.program_id(1)

    base = seg_ptr + seg * 3
    src_addr = tl.load(base)
    dst_off = tl.load(base + 1)
    count = tl.load(base + 2)

    out = out_ptr.to(tl.pointer_type(ELEM_DTYPE))
    src = src_addr.to(tl.pointer_type(ELEM_DTYPE))

    offs = tile * BLOCK + tl.arange(0, BLOCK)
    mask = offs < count
    # A source address of -1 marks a run that must stay zero (cuDNN always
    # reserves room for biases), so it is masked out and never dereferenced.
    val = tl.load(src + offs, mask=mask & (src_addr >= 0), other=0)
    tl.store(out + dst_off + offs, val, mask=mask)


def _build_copy_plan(
    weight_arr,
    weight_stride0,
    input_size,
    mode,
    hidden_size,
    proj_size,
    num_layers,
    bidirectional,
):
    """Reproduce the cuDNN flat-weight layout as a list of copy runs.

    The flat buffer holds, for every (layer, direction) group, the input
    matrices followed by the recurrent matrices (and the projection matrix for
    projected LSTMs); all biases of all groups are appended at the very end.
    """
    if mode not in _NUM_GATES:
        raise RuntimeError(f"cudnn_rnn_flatten_weight: unsupported mode {mode}")
    if num_layers < 1:
        raise RuntimeError(
            f"cudnn_rnn_flatten_weight: num_layers must be >= 1, got {num_layers}"
        )

    gates = _NUM_GATES[mode]
    num_dirs = 2 if bidirectional else 1
    has_proj = proj_size > 0
    # Width of the recurrent matrices, which is also the input width of every
    # layer except the first one.
    hidden_out = proj_size if has_proj else hidden_size
    num_weights = 2 + (1 if has_proj else 0)
    has_bias = weight_stride0 - num_weights == 2
    if not has_bias and weight_stride0 != num_weights:
        raise RuntimeError(
            "cudnn_rnn_flatten_weight: weight_stride0 "
            f"({weight_stride0}) does not match a weights-only ({num_weights}) "
            f"or weights-and-biases ({num_weights + 2}) group"
        )

    num_groups = num_layers * num_dirs
    if len(weight_arr) < num_groups * weight_stride0:
        raise RuntimeError(
            "cudnn_rnn_flatten_weight: number of layers mismatch, got "
            f"{len(weight_arr)} tensors for {num_groups} layer groups of "
            f"{weight_stride0} tensors"
        )

    # With biases the projection matrix is the last element of a group,
    # without biases it directly follows the two weight matrices.
    proj_slot = 4 if has_bias else 2

    runs = []
    offset = 0
    for group in range(num_groups):
        layer = group // num_dirs
        in_size = input_size if layer == 0 else num_dirs * hidden_out
        sizes = [gates * hidden_size * in_size, gates * hidden_size * hidden_out]
        if has_proj:
            sizes.append(proj_size * hidden_size)
        for k, size in enumerate(sizes):
            src = group * weight_stride0 + (k if k < 2 else proj_slot)
            runs.append((src, offset, size))
            offset += size

    bias_size = gates * hidden_size
    for group in range(num_groups):
        for k in (2, 3):
            if has_bias:
                runs.append((group * weight_stride0 + k, offset, bias_size))
            else:
                runs.append((-1, offset, bias_size))
            offset += bias_size

    for src, _, size in runs:
        if src < 0:
            continue
        if weight_arr[src].numel() != size:
            raise RuntimeError(
                "cudnn_rnn_flatten_weight: weight "
                f"{src} has {weight_arr[src].numel()} elements but the cuDNN "
                f"flat layout expects {size}"
            )

    return runs, offset


