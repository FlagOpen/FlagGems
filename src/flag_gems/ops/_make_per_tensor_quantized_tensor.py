    offs = pid * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
    mask = offs < n_elements
    src_off = tl.zeros([BLOCK], dtype=tl.int64)
    rem = offs
    if RANK > 1:
        c = rem // e1
        src_off += c * s0
        rem = rem % e1
    if RANK > 2:
        c = rem // e2
        src_off += c * s1
        rem = rem % e2
    if RANK > 3:
        c = rem // e3
        src_off += c * s2
        rem = rem % e3
    if RANK > 4:
        c = rem // e4
        src_off += c * s3
        rem = rem % e4
    if RANK > 5:
        c = rem // e5
        src_off += c * s4
        rem = rem % e5
    if RANK > 6:
        c = rem // e6
        src_off += c * s5
        rem = rem % e6
    if RANK > 7:
        c = rem // e7
        src_off += c * s6
        rem = rem % e7
    # After peeling dims 0..RANK-2 the remainder is the last coordinate.
    src_off += rem * s7
    tl.store(dst_ptr + offs, tl.load(src_ptr + src_off, mask=mask), mask=mask)


