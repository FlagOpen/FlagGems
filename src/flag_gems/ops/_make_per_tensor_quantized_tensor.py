# The integer storage dtype each quantized dtype reads its ``int_repr`` from:
# the output quantized dtype follows the payload's integer dtype (int8 -> qint8,
# uint8 -> quint8, int32 -> qint32); any other payload dtype has no CUDA kernel
# for ``aten::_empty_affine_quantized`` and raises NotImplementedError in ATen
# as well.
_QDTYPE_FROM_INT = {
    torch.int8: torch.qint8,
    torch.uint8: torch.quint8,
    torch.int32: torch.qint32,
}

# The gather kernel is specialized over ranks 1..8; the stride/suffix lists are
# padded to this compile-time width (unused dims are folded out by RANK).
_MAX_RANK = 8


