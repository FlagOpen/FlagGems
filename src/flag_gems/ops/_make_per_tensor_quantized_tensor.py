def _mptq_gather_strided(
    src_ptr,
    dst_ptr,
    n_elements,
    e1,
    e2,
    e3,
    e4,
    e5,
    e6,
    e7,
    s0,
    s1,
    s2,
    s3,
    s4,
    s5,
    s6,
    s7,  # source strides
    RANK: tl.constexpr,
    BLOCK: tl.constexpr,
):
    """Non-contiguous payload: gather elements into contiguous storage.

    The destination is contiguous, so a flat output index decomposes against
    the suffix products of the out sizes (``e_k`` = product of sizes[k:]):
    ``c_d = rem // e_{d+1}`` for d = 0..rank-2, and the last coordinate is the
    remainder itself. Each coordinate is re-based by the source stride.
    ``RANK`` folds unused trailing dims out at compile time.
    """
