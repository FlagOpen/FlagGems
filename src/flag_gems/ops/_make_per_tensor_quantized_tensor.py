def _wrap(int_repr, scale, zero_point):
    """Attach the per-tensor quantization metadata to the written storage.

    ``_empty_affine_quantized`` + ``set_`` shares the freshly written payload
    storage instead of forcing a second copy through quantized ``copy_``. The
    fp64 scale and int64 zero-point are stored bit-exactly by the factory, so
    the scalar qparams need no device work at all.
    """
    qdtype = _QDTYPE_FROM_INT[int_repr.dtype]
    result = torch._empty_affine_quantized(
        0,
        scale=scale,
        zero_point=zero_point,
        dtype=qdtype,
        device=int_repr.device,
        memory_format=torch.contiguous_format,
    )
    result.set_(
        int_repr.untyped_storage(),
        int_repr.storage_offset(),
        tuple(int_repr.shape),
        tuple(int_repr.stride()),
    )
    return result


