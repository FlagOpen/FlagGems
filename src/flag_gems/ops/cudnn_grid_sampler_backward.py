def _select_config(is_fp64, C, total_out):
    """Pick a launch configuration and clamp the tiles to the problem size."""
    block_p, block_c, num_warps = KERNEL_CONFIG_FP64 if is_fp64 else KERNEL_CONFIG
    block_p = min(block_p, triton.next_power_of_2(total_out))
    block_c = min(block_c, triton.next_power_of_2(C))
    return block_p, block_c, num_warps


