class MetadataBenchmark(base.Benchmark):
    def set_shapes(self, shape_file_path=None):
        # Small and large payloads demonstrate that metadata work is size independent.
        self.shapes = [(0,), (1,), (3, 4), (4096, 4096), (2, 3, 4, 5), (2, 3, 4, 5, 6)]

    def get_input_iter(self, dtype):
        for i, shape in enumerate(self.shapes):
            inp = torch.zeros(shape, dtype=dtype, device=self.device)
            if i == 2:
                inp = inp.t()
            elif i == 4:
                inp = inp.requires_grad_().view_as(inp)
            yield (inp,)


