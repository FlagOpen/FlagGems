# (nnz, shape) pairs for CSC inputs. ``ccol_indices`` only hands back the
# internal compressed-column view (O(1) in nnz), so the sweep varies the column
# count -- the metadata the harness touches -- while the values dtype follows
# the benchmark dtype sweep (ccol stays int64 like every default-constructed
# sparse tensor).
CCOL_INDICES_CASES = [
    (256, (64, 128)),
    (4096, (512, 512)),
    (65536, (2048, 2048)),
    (1048576, (4096, 8192)),
]


def _make_csc(nnz, shape, cur_dtype, device):
    """Valid CSC with ccol length ncols + 1 and row/values length nnz.

    Built on CPU (the bincount + cumsum pattern needs no device-side fill
    kernel) and moved to the benchmark device once.
    """
    nrows, ncols = shape
    counts = torch.bincount(
        torch.randint(0, ncols, (nnz,), dtype=torch.int64),
        minlength=ncols,
    )
    ccol = torch.zeros(ncols + 1, dtype=torch.int64)
    ccol[1:] = counts.cumsum(0)
    row = torch.randint(0, nrows, (nnz,), dtype=torch.int64)
    values = utils.generate_tensor_input((nnz,), cur_dtype, "cpu")
    return torch.sparse_csc_tensor(ccol, row, values, shape).to(device)


